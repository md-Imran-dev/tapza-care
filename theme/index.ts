export function deriveTheme(theme: ThemeColors) {
  const festive = theme.festival?.name === "diwali";
  return {
    colors: {
      ...theme,
      white: "#FFFFFF",
      whiteTranslucent: "#FFFFFF25",
      whiteTint: "#FFFFFF20",
      glass: "#FFFFFF14",
      onDarkSecondary: "#FFFFFFCC",
      onDarkMuted: "#FFFFFFBB",
      onDarkBorder: "#FFFFFF66",
      onDarkOutline: "#FFFFFF80",
      ink: theme.textPrimary,
      muted: theme.textSecondary,
      line: festive ? "#E7D4BE" : "#DDE8E3",
      green: "#166534",
      paleGreen: festive ? "#FFF0D5" : "#E6F4EF",
      peach: "#FFF1E6",
      orange: "#9A3412",
      blue: "#E8EEFF",
      indigo: "#3730A3",
      purple: "#F3E8FF",
      violet: "#6B21A8",
      amber: "#854D0E",
      red: "#991B1B",
      overlay: "rgba(5,20,18,0.78)",
      heroFade: "rgba(5,20,18,0.72)",
      inactive: festive ? "#80614D" : "#536F65",
      transparent: "transparent",
      tabActive: festive ? theme.primary : "#62568F",
      tabBackground: theme.background,
    },
    space,
    type,
    radius,
    lineHeight,
    tracking,
    metrics,
    motion: {
      reveal: 400,
      parallax: 0.12,
      dismissDistance: 110,
      sheetSpring: { damping: 24, stiffness: 240 },
      successFade: 220,
      successZoom: 320,
    },
  };
}
export function useTheme() {
  const theme = useCare((s) => s.config.theme);
  return useMemo(() => deriveTheme(theme), [theme]);
}
